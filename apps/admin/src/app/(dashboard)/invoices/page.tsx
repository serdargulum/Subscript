"use client";

import Link from "next/link";
import { useSearchParams } from "next/navigation";
import { Suspense, useCallback, useEffect, useState } from "react";
import {
  Card,
  CustomerLink,
  EmptyState,
  ErrorBanner,
  PageHeader,
  Pager,
  StatusBadge,
  SuccessBanner
} from "@/components/ui";
import { api, apiPost, queryString } from "@/lib/api";
import { formatDate, formatMoney } from "@/lib/format";
import type { Customer, Invoice, InvoiceStatus, Paged, Subscription } from "@/lib/types";

const pageSize = 20;
const statuses: Array<InvoiceStatus | ""> = ["", "Open", "Paid", "Cancelled"];

export default function InvoicesPage() {
  return (
    <Suspense
      fallback={
        <Card>
          <div className="loading">Loading invoices…</div>
        </Card>
      }
    >
      <InvoicesView />
    </Suspense>
  );
}

function InvoicesView() {
  const searchParams = useSearchParams();
  const initialStatus = searchParams.get("status");
  const subscriptionId = searchParams.get("subscriptionId") ?? "";

  const [data, setData] = useState<Paged<Invoice> | null>(null);
  const [subscriptions, setSubscriptions] = useState<Map<string, Subscription>>(new Map());
  const [customers, setCustomers] = useState<Map<string, Customer>>(new Map());
  const [page, setPage] = useState(1);
  const [status, setStatus] = useState<InvoiceStatus | "">(
    statuses.includes(initialStatus as InvoiceStatus) ? (initialStatus as InvoiceStatus) : ""
  );
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [message, setMessage] = useState<string | null>(null);
  const [busyId, setBusyId] = useState<string | null>(null);

  const load = useCallback(async () => {
    setLoading(true);
    setError(null);

    try {
      const [invoices, subscriptionList, customerList] = await Promise.all([
        api<Paged<Invoice>>(
          `/invoices${queryString({ page, pageSize, status, subscriptionId })}`
        ),
        api<Paged<Subscription>>("/subscriptions?page=1&pageSize=200"),
        api<Paged<Customer>>("/customers?page=1&pageSize=200")
      ]);

      setData(invoices);
      setSubscriptions(new Map(subscriptionList.items.map((item) => [item.id, item])));
      setCustomers(new Map(customerList.items.map((item) => [item.id, item])));
    } catch (loadError) {
      setError(loadError instanceof Error ? loadError.message : "Could not load invoices.");
    } finally {
      setLoading(false);
    }
  }, [page, status, subscriptionId]);

  useEffect(() => {
    void load();
  }, [load]);

  function customerFor(invoice: Invoice): { id: string; name: string } | null {
    const subscription = subscriptions.get(invoice.subscriptionId);
    if (!subscription) {
      return null;
    }

    const customer = customers.get(subscription.customerId);
    return customer ? { id: customer.id, name: customer.name } : null;
  }

  async function markPaid(invoice: Invoice) {
    if (!window.confirm(`Record a successful manual payment for ${formatMoney(invoice.amount, invoice.currency)}?`)) {
      return;
    }

    setBusyId(invoice.id);
    setError(null);
    setMessage(null);

    try {
      await apiPost("/payments", {
        invoiceId: invoice.id,
        method: "Manual",
        status: "Succeeded",
        paidAt: null,
        failureReason: null
      });
      setMessage("Payment recorded. Invoice is now paid.");
      await load();
    } catch (paymentError) {
      setError(paymentError instanceof Error ? paymentError.message : "Could not record the payment.");
    } finally {
      setBusyId(null);
    }
  }

  async function cancel(invoice: Invoice) {
    if (!window.confirm("Cancel this invoice?")) {
      return;
    }

    setBusyId(invoice.id);
    setError(null);
    setMessage(null);

    try {
      await api(`/invoices/${invoice.id}/cancel`, { method: "POST" });
      setMessage("Invoice cancelled.");
      await load();
    } catch (cancelError) {
      setError(cancelError instanceof Error ? cancelError.message : "Could not cancel the invoice.");
    } finally {
      setBusyId(null);
    }
  }

  return (
    <>
      <PageHeader
        title="Invoices"
        description={
          subscriptionId
            ? "Invoices for the selected subscription."
            : "All invoices generated by billing runs."
        }
        actions={
          <div className="toolbar">
            <div className="field">
              <label htmlFor="invoice-status">Status</label>
              <select
                id="invoice-status"
                value={status}
                onChange={(event) => {
                  setPage(1);
                  setStatus(event.target.value as InvoiceStatus | "");
                }}
              >
                {statuses.map((value) => (
                  <option key={value || "all"} value={value}>
                    {value || "All statuses"}
                  </option>
                ))}
              </select>
            </div>
            {subscriptionId ? (
              <Link className="button button-ghost" href="/invoices">
                Clear subscription filter
              </Link>
            ) : null}
          </div>
        }
      />

      <ErrorBanner message={error} />
      <SuccessBanner message={message} />

      <Card>
        {loading ? (
          <div className="loading">Loading invoices…</div>
        ) : !data || data.items.length === 0 ? (
          <EmptyState>No invoices match this view. Run billing to generate invoices.</EmptyState>
        ) : (
          <>
            <div className="table-wrap">
              <table>
                <thead>
                  <tr>
                    <th>Invoice</th>
                    <th>Customer</th>
                    <th>Plan</th>
                    <th>Period</th>
                    <th>Amount</th>
                    <th>Due</th>
                    <th>Status</th>
                    <th />
                  </tr>
                </thead>
                <tbody>
                  {data.items.map((invoice) => {
                    const customer = customerFor(invoice);

                    return (
                      <tr key={invoice.id}>
                        <td>
                          <Link className="table-link" href={`/invoices/${invoice.id}`}>
                            {invoice.invoiceNumber ?? invoice.id.slice(0, 8)}
                          </Link>
                        </td>
                        <td>
                          {customer ? (
                            <CustomerLink id={customer.id} name={customer.name} />
                          ) : (
                            <span className="table-muted">—</span>
                          )}
                        </td>
                        <td>
                          <div className="cell-stack">
                            <span>{invoice.planNameSnapshot}</span>
                            <small>{invoice.billingPeriodSnapshot}</small>
                          </div>
                        </td>
                        <td className="table-muted">
                          {formatDate(invoice.periodStart)} – {formatDate(invoice.periodEnd)}
                        </td>
                        <td>{formatMoney(invoice.amount, invoice.currency)}</td>
                        <td>{formatDate(invoice.dueDate)}</td>
                        <td>
                          <StatusBadge status={invoice.status} />
                        </td>
                        <td>
                          <div className="table-actions">
                            <Link className="button button-ghost button-small" href={`/invoices/${invoice.id}`}>
                              Open
                            </Link>
                            {invoice.status === "Open" ? (
                              <>
                                <button
                                  className="button button-small"
                                  type="button"
                                  onClick={() => markPaid(invoice)}
                                  disabled={busyId === invoice.id}
                                >
                                  Mark paid
                                </button>
                                <button
                                  className="button button-danger button-small"
                                  type="button"
                                  onClick={() => cancel(invoice)}
                                  disabled={busyId === invoice.id}
                                >
                                  Cancel
                                </button>
                              </>
                            ) : null}
                          </div>
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
            <Pager page={data.page} totalPages={data.totalPages} onPageChange={setPage} />
          </>
        )}
      </Card>
    </>
  );
}
